"""Read-only access to the Cardinal Ridge insurance database (SQLite).

The database is generated by `insurance_data/generate_data.py` and lives in backend/data/.
Tools and agents only ever open it READ-ONLY, so an AI mistake can never change a claim.
"""
import sqlite3
from datetime import date, timedelta
from pathlib import Path

from config.settings import settings
from exceptions import ConfigurationError


def db_path() -> Path:
    return Path(settings.insurance_db_path)


def connect() -> sqlite3.Connection:
    path = db_path()
    if not path.exists():
        raise ConfigurationError(
            f"Insurance database not found at {path}. Run: python insurance_data/generate_data.py"
        )
    con = sqlite3.connect(f"{path.as_uri()}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    return con


def query(sql: str, params: tuple = ()) -> list[dict]:
    with connect() as con:
        return [dict(r) for r in con.execute(sql, params).fetchall()]


def one(sql: str, params: tuple = ()) -> dict | None:
    rows = query(sql, params)
    return rows[0] if rows else None


def as_of_date() -> date:
    """'Today' inside the synthetic dataset (so deadline maths is reproducible)."""
    row = one("SELECT value FROM meta WHERE key='as_of_date'")
    return date.fromisoformat(row["value"]) if row else date.today()


def parse_as_of(value: str | None) -> str | None:
    """'' / None / 'latest' -> None (use the latest version). Otherwise a validated ISO date string."""
    if value is None or str(value).strip().lower() in ("", "latest", "current", "none", "null"):
        return None
    return date.fromisoformat(str(value).strip()).isoformat()


def version_filter(as_of: str | None, prefix: str = "") -> tuple[str, tuple]:
    """SQL fragment selecting the version of each record that was in force on `as_of` (default: the current one).

    The versioned tables (policyholders, policies, policy_coverages, claims) keep one row per change with
    valid_from / valid_to (exclusive); the latest row has is_current = 1 and valid_to NULL.
    """
    if as_of is None:
        return f"{prefix}is_current = 1", ()
    return f"({prefix}valid_from <= ? AND ({prefix}valid_to IS NULL OR {prefix}valid_to > ?))", (as_of, as_of)


def version_one(table: str, where: str, params: tuple, as_of: str | None = None) -> dict | None:
    """One record of a versioned table, as of a date (latest when as_of is None)."""
    flt, fparams = version_filter(as_of)
    return one(f"SELECT * FROM {table} WHERE {where} AND {flt}", (*params, *fparams))


def to_date(value: str | None) -> date | None:
    return date.fromisoformat(value) if value else None


def add_days(start: date, n: int, business: bool = False) -> date:
    if not business:
        return start + timedelta(days=n)
    while n > 0:
        start += timedelta(days=1)
        if start.weekday() < 5:
            n -= 1
    return start


def days_between(a: date, b: date, business: bool = False) -> int:
    """Whole days from a to b (negative if b is before a). Business mode skips weekends."""
    if not business:
        return (b - a).days
    step, count, cur = (1 if b >= a else -1), 0, a
    while cur != b:
        cur += timedelta(days=step)
        if cur.weekday() < 5:
            count += step
    return count
